"""
Final microscope conclusions: collect everything we learned,
contrast pre-fix and post-fix v17 numbers, and write a clean narrative
that lists the bugs we found, what is real signal, and what is noise.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)
sys.path.insert(0, str(ROOT_DIR))

REPORTS = Path("reports")
COMP_DIR = Path("models_v2/asof_comparison")
MICRO = REPORTS / "microscope"


def main() -> None:
    base = pd.read_csv(MICRO / "baselines.csv")
    cw_t = pd.read_csv(MICRO / "cw_timing.csv")
    io = pd.read_csv(MICRO / "insample_vs_oof.csv")
    fi = pd.read_csv(MICRO / "feature_importance.csv")
    py_df = pd.read_csv(MICRO / "per_year_errors.csv")
    phys = pd.read_csv(MICRO / "physical_target_sanity.csv")

    md: list[str] = []
    md.append("# Microscope audit — final conclusions\n\n")
    md.append(
        "Generated by `scripts/audit/microscope_audit.py` and "
        "`scripts/audit/microscope_final_summary.py`.\n\n"
    )

    md.append("## TL;DR\n\n")
    md.append(
        "1. **Critical leakage bug found**: `cropwise_asof_t_ha` was a feature in every "
        "model from v9 onward (it was never on the non-feature list). With it removed, "
        "all-crops 1 Sep flipped from ML-win to Cropwise-win, wheat 1 Sep moved "
        "to Cropwise, and feature importance no longer puts the Cropwise estimate as "
        "the #1 feature.\n"
    )
    md.append(
        "2. **Sunflower results were noise**: the naive `last_year` baseline reaches "
        "23.9% MAPE on the same rows where ML gets 25-26%. There is no real signal "
        "for sunflower at this dataset size.\n"
    )
    md.append(
        "3. **Wheat ML is real signal**: the same naive baselines sit at 40-62% MAPE while "
        "ML stays at 28-34%. ML beats them on R^2 too. So the wheat numbers are not a "
        "fluke.\n"
    )
    md.append(
        "4. **All-crops ML beats naive but not Cropwise on R^2**: ML stays at "
        "around 28-31% MAPE vs naive 34-47%, but R^2 stays close to 0 while Cropwise "
        "is at 0.25-0.34. ML predicts close to the train-year mean and only marginally "
        "ranks fields.\n"
    )
    md.append(
        "5. **Severe overfitting on a tiny dataset**: in-sample R^2 = 0.94-0.99 on the "
        "same data where OOF R^2 is around 0. This is the bottleneck: 127-180 rows is "
        "not enough to train CatBoost without memorizing.\n\n"
    )

    md.append("## 1. Naive baselines vs ML vs Cropwise (CW leak removed, same rows)\n\n")
    md.append(
        "MAPE in %, MAE/RMSE in t/ha, R^2 unitless. ML is the best v17 policy per "
        "scenario / date. Cropwise is the official as-of estimate. Naive baselines "
        "are walk-forward and predicted only on the same rows where ML produced an "
        "OOF prediction.\n\n"
    )
    cols_mape = [
        "scenario", "asof_label", "n_ml",
        "ml_mape", "cw_mape", "global_mean_mape", "crop_mean_mape",
        "field_mean_mape", "field_crop_mean_mape", "last_year_mape",
    ]
    md.append(base[cols_mape].round(2).to_markdown(index=False) + "\n\n")
    cols_mae = [
        "scenario", "asof_label", "ml_mae", "cw_mae",
        "global_mean_mae", "crop_mean_mae", "field_mean_mae",
        "field_crop_mean_mae", "last_year_mae",
    ]
    md.append("**MAE block**\n\n")
    md.append(base[cols_mae].round(3).to_markdown(index=False) + "\n\n")
    cols_r2 = [
        "scenario", "asof_label", "ml_r2", "cw_r2",
        "global_mean_r2", "crop_mean_r2", "field_mean_r2",
        "field_crop_mean_r2", "last_year_r2",
    ]
    md.append("**R^2 block**\n\n")
    md.append(base[cols_r2].round(3).to_markdown(index=False) + "\n\n")

    md.append("## 2. Cropwise as-of timing audit\n\n")
    md.append(
        "We pick the latest Cropwise estimate with date ≤ as-of. "
        "`min_offset_days = 0` confirms no future-leakage from Cropwise; "
        "`max_offset_days` of ~1 year shows that for some fields the latest available "
        "estimate is up to a year stale (the model still publishes them, but they are "
        "not refreshed).\n\n"
    )
    md.append(cw_t.round(2).to_markdown(index=False) + "\n\n")

    md.append("## 3. In-sample vs OOF gap (overfitting diagnostic)\n\n")
    md.append(
        "In-sample R^2 ≥ 0.93 vs OOF R^2 around 0 across all scenarios = clear "
        "overfitting. CatBoost happily memorizes 127-180 row datasets but cannot "
        "generalize to a new test year. This is the actual ceiling: it is dataset-size "
        "limited, not feature-quality limited.\n\n"
    )
    md.append(io.round(3).to_markdown(index=False) + "\n\n")

    md.append("## 4. Feature importance (CatBoost in-sample, 1 Aug, after CW leak removed)\n\n")
    md.append(
        "Top features after the fix: NDVI seasonal aggregates, NDVI anomalies, weather "
        "stress (water balance, VPD, hot days, May solar radiation). No Cropwise estimate, "
        "no field_id-driven memorization. This is what we want to see.\n\n"
    )
    for sc in ["sunflower", "wheat_combined", "all_crops"]:
        sub = (
            fi[fi["scenario"] == sc]
            .sort_values("importance", ascending=False)
            .head(15)
        )
        md.append(f"### {sc}\n\n")
        md.append(sub[["feature", "importance"]].round(2).to_markdown(index=False) + "\n\n")

    md.append("## 5. Per-year error breakdown (1 Aug)\n\n")
    md.append(
        "Where do ML and CW diverge year-by-year? `n_ml=0` means walk-forward did not "
        "have enough train rows yet; for those years only Cropwise is evaluated.\n\n"
    )
    sub = py_df[py_df["asof_tag"] == "08_01"].sort_values(["scenario", "year"]).copy()
    md.append(
        sub[
            [
                "scenario", "year", "n", "n_ml", "n_cw",
                "target_mean", "ml_mape", "ml_mae", "cw_mape", "cw_mae",
            ]
        ].round(3).to_markdown(index=False)
        + "\n\n"
    )

    md.append("## 6. physical_t_ha sanity\n\n")
    md.append(
        "`physical_t_ha = harvested_weight / tillable_area`. We require it to be the "
        "primary target source in v17. The distribution looks clean:\n\n"
    )
    md.append(
        f"- rows: {len(phys)}\n"
        f"- mean: {phys['physical_t_ha'].mean():.3f} t/ha\n"
        f"- median: {phys['physical_t_ha'].median():.3f} t/ha\n"
        f"- min: {phys['physical_t_ha'].min():.3f} t/ha\n"
        f"- max: {phys['physical_t_ha'].max():.3f} t/ha\n"
        f"- abnormally low (<0.3): {int(phys['abnormally_low'].sum())}\n"
        f"- abnormally high (>12): {int(phys['abnormally_high'].sum())}\n\n"
    )

    md.append("## 7. What this means for the dissertation narrative\n\n")
    md.append(
        "Honest framing for the paper:\n\n"
    )
    md.append(
        "- The most important methodological contribution is the multi-stage data-quality "
        "pipeline: factual target reconstruction (v7), unit-error fix from a Russian "
        "legacy sheet (v12), conflict-clean sensitivity (v16), and strict cross-source "
        "target priority (v17). Each step has a measurable effect on metrics.\n"
    )
    md.append(
        "- The Cropwise-leak bug is itself a finding: any prior published comparison that "
        "uses the platform's own real-time estimate as a feature is overstating ML "
        "performance.\n"
    )
    md.append(
        "- ML beats Cropwise on `all_crops` and `wheat` MAPE only at 1 Jul / 1 Aug. By 1 Sep "
        "Cropwise narrows the gap or wins. This is consistent with Cropwise getting more "
        "in-season signal closer to harvest.\n"
    )
    md.append(
        "- Cropwise wins on R^2 / MAE / RMSE everywhere except sunflower at 1 Jul. ML "
        "ranking ability is weak because the dataset is tiny (n_train ≤ 100 in walk-forward "
        "folds).\n"
    )
    md.append(
        "- Sunflower numbers should not be claimed as ML beats Cropwise: the naive "
        "last-year baseline is at the same level as ML, so the difference vs Cropwise on "
        "sunflower is statistical noise.\n\n"
    )

    md.append("## 8. Decision tree for next step\n\n")
    md.append(
        "Three options, ranked by effort:\n\n"
        "1. **Stop here, write up honestly.** Frame the paper around the data-quality pipeline "
        "and the Cropwise-leak finding. Report MAPE/MAE/RMSE/R^2 side by side, claim ML wins "
        "MAPE at 1 Jul/1 Aug for `all_crops` and `wheat`, do not claim ranking superiority. "
        "This is publishable as-is.\n"
        "2. **Expand the data first.** The bottleneck is n=127. Three concrete ways to grow it:\n"
        "   a) Fetch geometry + NDVI for the remaining ~507 fields via Open Platform with a "
        "fresh API token (the cheapest big win).\n"
        "   b) Hand-map field coordinates from the user's farm records and pull NDVI from "
        "Sentinel-2 / MOD13Q1 directly.\n"
        "   c) Pool with neighboring farms in the same VKO region if a partner provides data.\n"
        "3. **Improve the model on the current dataset.** Diminishing returns, but worth a try:\n"
        "   - Add NDRE / EVI to compensate for NDVI saturation in dense wheat canopies.\n"
        "   - Use blend regression: predict `target - crop_mean` as residual on top of a "
        "crop-mean prior. This often helps small datasets generalize.\n"
        "   - Try LightGBM with monotonic constraints on agronomic features.\n"
        "   - Hyperparameter sweep with explicit early-stopping on a held-out year, not "
        "random 20% (current setup is leaky inside the train fold).\n\n"
    )

    out = REPORTS / "MICROSCOPE_FINAL.md"
    out.write_text("".join(md), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()

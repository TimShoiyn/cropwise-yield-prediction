"""
v12 error analysis.

For each scenario/date, use best v12 config from asof_results_v12.csv,
recompute OOF walk-forward predictions, and compare ML vs Cropwise by year,
field, and crop.

Outputs:
  - reports/v12_oof_predictions_best.csv
  - reports/V12_ERROR_ANALYSIS.md
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)
sys.path.insert(0, str(ROOT_DIR))

from scripts.asof.train_compare_asof_v9 import (  # noqa: E402
    COMP_DIR,
    DATA_RAW,
    PARAM_SETS,
    REPORTS,
    attach_cropwise,
    cropwise_table,
    load_dataset,
    metrics,
    walk_forward_oof,
)

SCENARIOS = {
    "sunflower": ["sunflower"],
    "wheat_combined": ["wheat_spring", "wheat_winter"],
    "all_crops": None,
}

MODEL_TO_PARAMS = {
    "v12_default": ("default", True),
    "v12_shallow_l10": ("shallow_l10", True),
    "v12_shallow_l30": ("shallow_l30", True),
    "v12_mae_l30": ("mae_l30", True),
    "v12_no_field_id": ("shallow_l10", False),
}


def code(df_or_text) -> str:
    if isinstance(df_or_text, pd.DataFrame):
        text = df_or_text.to_string(index=False)
    elif isinstance(df_or_text, pd.Series):
        text = df_or_text.to_string()
    else:
        text = str(df_or_text)
    return f"\n```\n{text}\n```\n"


def build_predictions() -> pd.DataFrame:
    summary = pd.read_csv(COMP_DIR / "asof_results_v12.csv")
    best = summary.sort_values(["scenario", "asof_tag", "mape"]).groupby(["scenario", "asof_tag"], as_index=False).first()
    cw = cropwise_table()
    fields = pd.read_csv(DATA_RAW / "fields.csv")[["id", "name", "tillable_area"]].rename(
        columns={"id": "field_id", "name": "field_name_csv"}
    )
    parts = []
    for _, row in best.iterrows():
        scenario = row["scenario"]
        tag = row["asof_tag"]
        model = row["model"]
        params_name, use_field_id = MODEL_TO_PARAMS[model]
        df = attach_cropwise(load_dataset("v12", tag, SCENARIOS[scenario]), tag, cw)
        pred = walk_forward_oof(df, PARAM_SETS[params_name], use_field_id=use_field_id)
        out = df.assign(ml_pred=pred)
        out = out.dropna(subset=["ml_pred", "cropwise_asof_t_ha"]).copy()
        out["scenario"] = scenario
        out["asof_tag"] = tag
        out["model"] = model
        out["ml_error"] = out["ml_pred"] - out["target_yield_t_ha"]
        out["cw_error"] = out["cropwise_asof_t_ha"] - out["target_yield_t_ha"]
        out["ml_abs_error"] = out["ml_error"].abs()
        out["cw_abs_error"] = out["cw_error"].abs()
        out["ml_mape_row"] = out["ml_abs_error"] / out["target_yield_t_ha"].replace(0, np.nan) * 100
        out["cw_mape_row"] = out["cw_abs_error"] / out["target_yield_t_ha"].replace(0, np.nan) * 100
        out["ml_wins"] = out["ml_abs_error"] < out["cw_abs_error"]
        out = out.merge(fields, on="field_id", how="left")
        keep = [
            "scenario", "asof_tag", "model", "field_id", "field_name_csv", "year", "standard_name", "prod_crop_ru",
            "target_yield_t_ha", "ml_pred", "cropwise_asof_t_ha", "ml_error", "cw_error",
            "ml_abs_error", "cw_abs_error", "ml_mape_row", "cw_mape_row", "ml_wins", "tillable_area",
        ]
        parts.append(out[keep])
    return pd.concat(parts, ignore_index=True)


def agg_metrics(g: pd.DataFrame) -> pd.Series:
    ml = metrics(g["target_yield_t_ha"], g["ml_pred"])
    cw = metrics(g["target_yield_t_ha"], g["cropwise_asof_t_ha"])
    return pd.Series({
        "n": len(g),
        "ml_mape": ml["mape"],
        "cw_mape": cw["mape"],
        "ml_mae": ml["mae"],
        "cw_mae": cw["mae"],
        "ml_rmse": ml["rmse"],
        "cw_rmse": cw["rmse"],
        "ml_win_rate": g["ml_wins"].mean() * 100,
        "mean_target": g["target_yield_t_ha"].mean(),
    })


def main() -> None:
    preds = build_predictions()
    pred_path = REPORTS / "v12_oof_predictions_best.csv"
    preds.to_csv(pred_path, index=False)

    md: list[str] = ["# v12 Error Analysis\n\n"]
    md.append("Generated by `scripts/audit/error_analysis_v12.py`. Uses best v12 model per scenario/date with walk-forward OOF predictions.\n\n")
    md.append(f"Predictions saved to `{pred_path}`.\n\n")

    md.append("## 1. Overall by scenario/date\n")
    overall = preds.groupby(["scenario", "asof_tag", "model"]).apply(agg_metrics, include_groups=False).reset_index()
    md.append(code(overall.round(3)))

    md.append("\n## 2. By year (all_crops)\n")
    allc = preds[preds["scenario"] == "all_crops"].copy()
    by_year = allc.groupby(["asof_tag", "year"]).apply(agg_metrics, include_groups=False).reset_index()
    md.append(code(by_year.round(3)))

    md.append("\n## 3. By crop (all_crops)\n")
    by_crop = allc.groupby(["asof_tag", "standard_name"]).apply(agg_metrics, include_groups=False).reset_index()
    md.append(code(by_crop.sort_values(["asof_tag", "ml_mape"]).round(3)))

    md.append("\n## 4. Worst ML misses\n")
    worst_ml = preds.sort_values("ml_abs_error", ascending=False).head(40)
    md.append(code(worst_ml[[
        "scenario", "asof_tag", "field_id", "field_name_csv", "year", "standard_name",
        "target_yield_t_ha", "ml_pred", "cropwise_asof_t_ha", "ml_abs_error", "cw_abs_error", "ml_wins",
    ]].round(3)))

    md.append("\n## 5. Biggest ML wins vs Cropwise\n")
    wins = preds.assign(advantage=preds["cw_abs_error"] - preds["ml_abs_error"]).sort_values("advantage", ascending=False).head(40)
    md.append(code(wins[[
        "scenario", "asof_tag", "field_id", "field_name_csv", "year", "standard_name",
        "target_yield_t_ha", "ml_pred", "cropwise_asof_t_ha", "ml_abs_error", "cw_abs_error", "advantage",
    ]].round(3)))

    md.append("\n## 6. Biggest Cropwise wins vs ML\n")
    losses = preds.assign(disadvantage=preds["ml_abs_error"] - preds["cw_abs_error"]).sort_values("disadvantage", ascending=False).head(40)
    md.append(code(losses[[
        "scenario", "asof_tag", "field_id", "field_name_csv", "year", "standard_name",
        "target_yield_t_ha", "ml_pred", "cropwise_asof_t_ha", "ml_abs_error", "cw_abs_error", "disadvantage",
    ]].round(3)))

    md.append("\n## 7. Interpretation\n\n")
    md.append("- Use `ml_win_rate` to discuss where our model systematically beats Cropwise row-by-row, not only by average MAPE.\n")
    md.append("- Rows in 'Worst ML misses' are the first candidates for manual agronomic inspection and feature/label audit.\n")
    md.append("- If one year dominates errors, the next bug hunt should focus on target/source consistency for that year.\n")

    out = REPORTS / "V12_ERROR_ANALYSIS.md"
    out.write_text("".join(md), encoding="utf-8")
    print(f"Wrote {pred_path}")
    print(f"Wrote {out}")
    print(overall.round(3).to_string(index=False))
    print("\nWorst ML misses:")
    print(worst_ml[["scenario", "asof_tag", "field_id", "year", "standard_name", "target_yield_t_ha", "ml_pred", "ml_abs_error", "cw_abs_error"]].head(15).round(3).to_string(index=False))


if __name__ == "__main__":
    main()

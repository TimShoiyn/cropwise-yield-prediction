"""
Deep data audit — pass over every raw and processed source.

Goal: surface unused data, hidden inconsistencies, leakage candidates and
target outliers we should investigate before further modeling.

Outputs:
  - reports/DATA_DEEP_AUDIT.md  (human readable conclusions and findings)
  - reports/figures/audit/*.png
"""

from __future__ import annotations

import os
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)

DATA_RAW = Path("data_raw")
DATA_PROCESSED = Path("data_processed")
REPORTS = Path("reports")
FIGS = REPORTS / "figures" / "audit"
FIGS.mkdir(parents=True, exist_ok=True)

SECTIONS: list[str] = []


def section(title: str) -> None:
    SECTIONS.append(f"\n## {title}\n")


def line(text: str = "") -> None:
    SECTIONS.append(text + "\n")


def code(text: str) -> None:
    SECTIONS.append("\n```\n" + text + "\n```\n")


def fig(path: Path, alt: str) -> None:
    rel = path.relative_to(REPORTS).as_posix()
    SECTIONS.append(f"\n![{alt}]({rel})\n")


def header() -> None:
    SECTIONS.append("# Deep Data Audit\n\n")
    line("Generated by `scripts/audit/deep_data_audit.py`.")
    line("Purpose: find what's unused, what's broken, what could leak.\n")


def audit_file_inventory() -> None:
    section("1. Raw file inventory")
    rows = []
    for path in sorted(DATA_RAW.glob("*.csv")):
        try:
            head = pd.read_csv(path, nrows=1)
            cols_n = head.shape[1]
        except Exception:
            cols_n = -1
        try:
            nrows = sum(1 for _ in path.open()) - 1
        except Exception:
            nrows = -1
        rows.append({
            "file": path.name,
            "size_kb": int(path.stat().st_size / 1024),
            "rows": nrows,
            "cols": cols_n,
        })
    inv = pd.DataFrame(rows).sort_values("size_kb", ascending=False)
    code(inv.to_string(index=False))



"""
Audit productivity_data.csv mapping to fields.csv and factual targets.

This file is crucial: it contains Russian field names, VKO region, fact yield
(centner/ha), and forecast yield. For the 30 fields in fields.csv, names match
exactly after normalization.

Output: reports/PRODUCTIVITY_DATA_MAPPING_AUDIT.md
"""

from __future__ import annotations

import os
import re
from pathlib import Path

import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)
DATA_RAW = Path("data_raw")
DATA_PROCESSED = Path("data_processed")
REPORTS = Path("reports")


def norm(value) -> str:
    if pd.isna(value):
        return ""
    text = str(value).lower().replace("ё", "е")
    text = re.sub(r"[^а-яa-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def main() -> None:
    fields = pd.read_csv(DATA_RAW / "fields.csv")
    prod = pd.read_csv(DATA_RAW / "productivity_data.csv")
    fields["field_name_norm"] = fields["name"].map(norm)
    prod["field_name_norm"] = prod["Поле"].map(norm)
    matched = prod.merge(
        fields[["id", "name", "field_name_norm", "lat", "long", "tillable_area"]],
        on="field_name_norm",
        how="inner",
    )
    matched = matched.rename(columns={"id": "field_id", "Год": "year"})
    matched["prod_fact_t_ha"] = pd.to_numeric(matched["урожайность факт ц/га"], errors="coerce") / 10.0
    matched["prod_forecast_t_ha"] = pd.to_numeric(matched["урожайность прогноз ц/га"], errors="coerce") / 10.0

    target = pd.read_csv(DATA_PROCESSED / "targets_factual_t_ha.csv")
    target = target[target["kept"]].copy()
    target = target[["field_id", "year", "standard_name", "target_yield_t_ha", "target_source"]]
    cmp = matched.merge(target, on=["field_id", "year"], how="inner")
    cmp = cmp.dropna(subset=["prod_fact_t_ha", "target_yield_t_ha"]).copy()
    cmp["diff_prod_fact_minus_target"] = cmp["prod_fact_t_ha"] - cmp["target_yield_t_ha"]
    cmp["abs_diff"] = cmp["diff_prod_fact_minus_target"].abs()

    out_cmp = REPORTS / "productivity_data_vs_targets_mismatches.csv"
    cmp.sort_values("abs_diff", ascending=False).to_csv(out_cmp, index=False)

    md = ["# Productivity Data Mapping Audit\n\n"]
    md.append("Generated by `scripts/audit/audit_productivity_data_mapping.py`.\n\n")
    md.append("## Key finding\n\n")
    md.append("`productivity_data.csv` has Russian field names, VKO region, fact yield in `ц/га`, and forecast yield in `ц/га`. ")
    md.append("All 30 fields from `fields.csv` match exactly by normalized field name. This gives an independent target/forecast table for our current 30-field dataset.\n\n")
    md.append("## Coverage\n\n")
    md.append(f"- `productivity_data.csv` unique field names: {prod['Поле'].nunique()}\n")
    md.append(f"- exact matched field names to `fields.csv`: {matched['field_id'].nunique()} / {fields['id'].nunique()}\n")
    md.append(f"- exact matched rows: {len(matched)}\n")
    md.append(f"- rows with fact+forecast values: {matched.dropna(subset=['prod_fact_t_ha', 'prod_forecast_t_ha']).shape[0]}\n")
    md.append(f"- overlap with current factual target: {len(cmp)}\n\n")

    md.append("## Cropwise forecast in productivity_data on exact-matched rows\n\n")
    m = matched.dropna(subset=["prod_fact_t_ha", "prod_forecast_t_ha"]).copy()
    err = m["prod_forecast_t_ha"] - m["prod_fact_t_ha"]
    forecast_metrics = pd.DataFrame([{
        "n": len(m),
        "bias": err.mean(),
        "mae": err.abs().mean(),
        "rmse": (err.pow(2).mean()) ** 0.5,
        "mape_%": (err.abs() / m["prod_fact_t_ha"]).mean() * 100,
    }]).round(3)
    md.append(forecast_metrics.to_markdown(index=False))
    md.append("\n\n")

    md.append("## Current target vs productivity_data fact\n\n")
    md.append(cmp[["prod_fact_t_ha", "target_yield_t_ha", "diff_prod_fact_minus_target"]].describe().round(3).to_markdown())
    md.append("\n\n")
    md.append("## Worst mismatches\n\n")
    cols = [
        "field_id", "name", "year", "Культура", "standard_name",
        "prod_fact_t_ha", "target_yield_t_ha", "target_source", "diff_prod_fact_minus_target", "abs_diff",
    ]
    md.append(cmp.sort_values("abs_diff", ascending=False)[cols].head(30).round(3).to_markdown(index=False))
    md.append("\n\n")
    md.append("## Interpretation\n\n")
    md.append("This shows the previous factual-target normalization still failed in some low-yield years. ")
    md.append("Example: wheat 2020 has `0.578 t/ha` in `productivity_data`, but current target has `5.780 t/ha`. ")
    md.append("The old rule divided by 10 only when the value exceeded a crop-specific cap, so low catastrophic yields in `ц/га` were not corrected.\n\n")
    md.append("Next: build v12 by overriding exact-matched current targets with `productivity_data` fact values converted from `ц/га` to `t/ha`.\n")

    out = REPORTS / "PRODUCTIVITY_DATA_MAPPING_AUDIT.md"
    out.write_text("".join(md), encoding="utf-8")
    print(f"Wrote {out}")
    print(f"Wrote {out_cmp}")
    print(cmp.sort_values("abs_diff", ascending=False)[cols].head(20).round(3).to_string(index=False))


if __name__ == "__main__":
    main()

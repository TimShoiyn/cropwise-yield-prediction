"""
Target conflict audit for v15.

Compares productivity_data factual target (c/ha -> t/ha) against combine
yield_maps for exact-matched fields/years. Flags conflicts and cross-references
v12/v15 high-yield misses.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)

DATA_RAW = Path("data_raw")
REPORTS = Path("reports")
CONFLICT_THRESHOLD = 1.0


def norm(value) -> str:
    if pd.isna(value):
        return ""
    text = str(value).lower().replace("ё", "е")
    text = re.sub(r"[^а-яa-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def pick_yield_value(row: pd.Series) -> float:
    for col in ["external_average", "totals.result.average.value"]:
        value = pd.to_numeric(row.get(col), errors="coerce")
        if pd.notna(value) and 0.1 <= float(value) <= 12.0:
            return float(value)
    value = pd.to_numeric(row.get("calculated_average"), errors="coerce")
    units = str(row.get("units", ""))
    if pd.notna(value):
        value = float(value)
        if units == "tonn_per_ha" and 0.1 <= value <= 12.0:
            return value
        if units == "tonn_per_acre" and 0.1 <= value <= 6.0:
            return value * 2.47105381
    return np.nan


def productivity_exact() -> pd.DataFrame:
    fields = pd.read_csv(DATA_RAW / "fields.csv")[["id", "name"]].rename(columns={"id": "field_id", "name": "field_name"})
    fields["field_name_norm"] = fields["field_name"].map(norm)
    prod = pd.read_csv(DATA_RAW / "productivity_data.csv")
    prod["field_name_norm"] = prod["Поле"].map(norm)
    prod = prod.rename(columns={"Год": "year", "Культура": "prod_crop_ru"})
    prod["prod_fact_t_ha"] = pd.to_numeric(prod["урожайность факт ц/га"], errors="coerce") / 10.0
    prod["prod_forecast_t_ha"] = pd.to_numeric(prod["урожайность прогноз ц/га"], errors="coerce") / 10.0
    out = prod.merge(fields, on="field_name_norm", how="inner")
    out = out.dropna(subset=["prod_fact_t_ha"]).copy()
    out["field_id"] = out["field_id"].astype(int)
    out["year"] = out["year"].astype(int)
    return out[["field_id", "field_name", "year", "prod_crop_ru", "prod_fact_t_ha", "prod_forecast_t_ha"]]


def yield_maps_agg() -> pd.DataFrame:
    ym = pd.read_csv(DATA_RAW / "yield_maps.csv", low_memory=False)
    ym["created_at"] = pd.to_datetime(ym["created_at"], errors="coerce", utc=True).dt.tz_convert(None)
    ym["year"] = ym["created_at"].dt.year
    ym["yield_map_t_ha"] = ym.apply(pick_yield_value, axis=1)
    ym = ym.dropna(subset=["field_id", "year", "yield_map_t_ha"]).copy()
    ym["field_id"] = ym["field_id"].astype(int)
    ym["year"] = ym["year"].astype(int)
    ym = ym[(ym["yield_map_t_ha"] >= 0.2) & (ym["yield_map_t_ha"] <= 10.0)]
    return ym.groupby(["field_id", "year"]).agg(
        yield_map_n=("yield_map_t_ha", "size"),
        yield_map_mean_t_ha=("yield_map_t_ha", "mean"),
        yield_map_std_t_ha=("yield_map_t_ha", "std"),
        yield_map_min_t_ha=("yield_map_t_ha", "min"),
        yield_map_max_t_ha=("yield_map_t_ha", "max"),
        yield_map_values=("yield_map_t_ha", lambda s: ";".join(f"{v:.2f}" for v in s.tolist()[:20])),
    ).reset_index()


def code(df_or_text) -> str:
    if isinstance(df_or_text, pd.DataFrame):
        text = df_or_text.to_string(index=False)
    else:
        text = str(df_or_text)
    return f"\n```\n{text}\n```\n"


def main() -> None:
    prod = productivity_exact()
    ym = yield_maps_agg()
    cmp = prod.merge(ym, on=["field_id", "year"], how="inner")
    cmp["diff_prod_minus_map"] = cmp["prod_fact_t_ha"] - cmp["yield_map_mean_t_ha"]
    cmp["abs_diff"] = cmp["diff_prod_minus_map"].abs()
    cmp["conflict_gt_1t"] = cmp["abs_diff"] > CONFLICT_THRESHOLD

    high_miss_path = REPORTS / "v12_high_yield_miss_audit.csv"
    if high_miss_path.exists():
        hm = pd.read_csv(high_miss_path)
        hm_keys = hm[["field_id", "year"]].drop_duplicates()
        hm_keys["in_high_yield_miss_audit"] = True
        cmp = cmp.merge(hm_keys, on=["field_id", "year"], how="left")
        cmp["in_high_yield_miss_audit"] = cmp["in_high_yield_miss_audit"].fillna(False)
    else:
        cmp["in_high_yield_miss_audit"] = False

    out_csv = REPORTS / "target_conflicts_productivity_vs_yield_maps.csv"
    cmp.sort_values("abs_diff", ascending=False).to_csv(out_csv, index=False)

    conflicts = cmp[cmp["conflict_gt_1t"]].sort_values("abs_diff", ascending=False)
    md = ["# Target Conflict Audit — productivity_data vs yield_maps\n\n"]
    md.append("Generated by `scripts/audit/target_conflict_audit_v15.py`.\n\n")
    md.append(f"Detailed CSV: `{out_csv}`.\n\n")
    md.append("## Coverage\n\n")
    md.append(f"- productivity exact rows: {len(prod)}\n")
    md.append(f"- yield-map `(field_id, year)` pairs: {len(ym)}\n")
    md.append(f"- overlap rows: {len(cmp)}\n")
    md.append(f"- conflicts > {CONFLICT_THRESHOLD} t/ha: {len(conflicts)}\n\n")

    md.append("## Conflicts >1 t/ha\n")
    show = [
        "field_id", "field_name", "year", "prod_crop_ru", "prod_fact_t_ha", "yield_map_mean_t_ha",
        "yield_map_n", "yield_map_values", "diff_prod_minus_map", "abs_diff", "in_high_yield_miss_audit",
    ]
    md.append(code(conflicts[show].round(3)))

    md.append("\n## High-yield miss conflicts\n")
    hm_conf = cmp[cmp["in_high_yield_miss_audit"]].sort_values("abs_diff", ascending=False)
    md.append(code(hm_conf[show].round(3)))

    md.append("\n## Interpretation\n\n")
    md.append("Rows with large positive `prod_fact_t_ha - yield_map_mean_t_ha` may be overestimated in `productivity_data`, or yield maps may represent partial/incorrect harvest maps. These rows should not be used blindly as ground truth in the scientific comparison.\n")
    md.append("For modeling, keep v12/v15 results as current baseline, but mark these rows as target-risk and run a sensitivity experiment excluding them next.\n")

    out_md = REPORTS / "TARGET_CONFLICT_AUDIT_V15.md"
    out_md.write_text("".join(md), encoding="utf-8")
    print(f"Wrote {out_csv}")
    print(f"Wrote {out_md}")
    print(conflicts[show].round(3).to_string(index=False))


if __name__ == "__main__":
    main()

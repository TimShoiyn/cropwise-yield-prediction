"""
v12 pipeline sanity audit.

Checks:
  - no obvious leakage columns are present in feature set
  - productivity_data exact-name target merge is stable
  - target units/ranges are plausible
  - crop labels from Cropwise history and productivity_data agree
  - duplicates/missing values/year coverage

Output: reports/V12_PIPELINE_SANITY_AUDIT.md
"""

from __future__ import annotations

import os
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)

DATA_RAW = Path("data_raw")
DATA_PROCESSED = Path("data_processed")
REPORTS = Path("reports")
ASOF_TAGS = ["07_01", "08_01", "09_01"]

RU_CROP_MAP = {
    "подсолнечник": "sunflower",
    "пшеница яровая": "wheat_spring",
    "пшеница яровая семеноводство": "wheat_spring",
    "пшеница озимая": "wheat_winter",
    "ячмень яровой": "barley_spring",
    "рапс яровой": "oil_seed_raps_spring",
    "рапс озимый": "oil_seed_raps_winter",
    "горох": "pea",
    "соя": "soya",
    "кукуруза": "maize",
    "сафлор": "safflower",
    "пар": "fallow",
}

LEAKAGE_PATTERNS = [
    "forecast",
    "estimate_value",
    "estimate_history",
    "cropwise",
    "old_target",
    "target_delta",
    "yield_map",
    "prod_fact",
    "prod_forecast",
    "урожайность",
]

NON_FEATURE = {
    "field_id",
    "year",
    "target_yield_t_ha",
    "target_source",
    "unit_fix_applied",
    "standard_name",
    "sowing_date",
    "harvesting_date",
    "field_name",
    "prod_crop_ru",
}


def norm(value) -> str:
    if pd.isna(value):
        return ""
    text = str(value).lower().replace("ё", "е")
    text = re.sub(r"[^а-яa-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def code(df_or_text) -> str:
    if isinstance(df_or_text, pd.DataFrame):
        text = df_or_text.to_string(index=False)
    elif isinstance(df_or_text, pd.Series):
        text = df_or_text.to_string()
    else:
        text = str(df_or_text)
    return f"\n```\n{text}\n```\n"


def feature_columns(df: pd.DataFrame) -> list[str]:
    return [c for c in df.columns if c not in NON_FEATURE]


def main() -> None:
    md: list[str] = ["# v12 Pipeline Sanity Audit\n\n"]
    md.append("Generated by `scripts/audit/pipeline_sanity_v12.py`.\n\n")

    # Target mapping audit.
    fields = pd.read_csv(DATA_RAW / "fields.csv")[["id", "name"]].rename(columns={"id": "field_id", "name": "field_name_csv"})
    fields["field_name_norm"] = fields["field_name_csv"].map(norm)
    prod = pd.read_csv(DATA_RAW / "productivity_data.csv")
    prod["field_name_norm"] = prod["Поле"].map(norm)
    prod = prod.rename(columns={"Год": "year", "Культура": "prod_crop_ru"})
    prod["prod_fact_t_ha"] = pd.to_numeric(prod["урожайность факт ц/га"], errors="coerce") / 10.0
    matched = prod.merge(fields, on="field_name_norm", how="inner")
    matched = matched.dropna(subset=["prod_fact_t_ha"]).copy()

    md.append("## 1. productivity_data exact field-name mapping\n\n")
    md.append(f"- unique field names in productivity_data: {prod['Поле'].nunique()}\n")
    md.append(f"- fields.csv fields: {fields['field_id'].nunique()}\n")
    md.append(f"- exact-matched fields: {matched['field_id'].nunique()}\n")
    md.append(f"- exact-matched fact rows: {len(matched)}\n")
    md.append(f"- target year range: {int(matched['year'].min())}..{int(matched['year'].max())}\n\n")

    # Dataset checks per tag.
    all_rows = []
    bad_leakage_rows = []
    label_mismatch_rows = []
    duplicate_rows = []
    high_missing_rows = []

    for tag in ASOF_TAGS:
        df = pd.read_csv(DATA_PROCESSED / f"ml_dataset_clean_v12_asof_{tag}.csv")
        fcols = feature_columns(df)
        suspicious = [c for c in fcols if any(p in c.lower() for p in LEAKAGE_PATTERNS)]
        for c in suspicious:
            bad_leakage_rows.append({"asof_tag": tag, "column": c})

        dup = df[df.duplicated(["field_id", "year"], keep=False)]
        for _, r in dup.iterrows():
            duplicate_rows.append({"asof_tag": tag, "field_id": r["field_id"], "year": r["year"]})

        df["prod_crop_std"] = df["prod_crop_ru"].map(lambda x: RU_CROP_MAP.get(norm(x), np.nan))
        mismatch = df[
            df["prod_crop_std"].notna()
            & df["standard_name"].notna()
            & (df["prod_crop_std"] != df["standard_name"])
        ]
        for _, r in mismatch.iterrows():
            label_mismatch_rows.append({
                "asof_tag": tag,
                "field_id": int(r["field_id"]),
                "year": int(r["year"]),
                "standard_name": r["standard_name"],
                "prod_crop_ru": r["prod_crop_ru"],
                "prod_crop_std": r["prod_crop_std"],
                "target_yield_t_ha": r["target_yield_t_ha"],
            })

        miss = df[fcols].isna().mean().sort_values(ascending=False)
        for col, ratio in miss[miss > 0.8].items():
            high_missing_rows.append({"asof_tag": tag, "column": col, "missing_ratio": ratio})

        all_rows.append({
            "asof_tag": tag,
            "rows": len(df),
            "fields": df["field_id"].nunique(),
            "years": f"{int(df['year'].min())}..{int(df['year'].max())}",
            "feature_cols": len(fcols),
            "target_min": df["target_yield_t_ha"].min(),
            "target_p05": df["target_yield_t_ha"].quantile(0.05),
            "target_median": df["target_yield_t_ha"].median(),
            "target_p95": df["target_yield_t_ha"].quantile(0.95),
            "target_max": df["target_yield_t_ha"].max(),
            "target_na": df["target_yield_t_ha"].isna().sum(),
            "duplicate_field_year": len(dup),
            "suspicious_feature_cols": len(suspicious),
            "crop_label_mismatches": len(mismatch),
        })

    md.append("## 2. v12 dataset overview\n")
    overview = pd.DataFrame(all_rows).round(3)
    md.append(code(overview))

    md.append("## 3. Leakage column scan\n")
    if bad_leakage_rows:
        md.append("Potential leakage columns found in feature set. Review/remove before training.\n")
        md.append(code(pd.DataFrame(bad_leakage_rows)))
    else:
        md.append("No obvious leakage columns found in v12 feature set.\n")

    md.append("\n## 4. Duplicate `(field_id, year)` scan\n")
    if duplicate_rows:
        md.append(code(pd.DataFrame(duplicate_rows)))
    else:
        md.append("No duplicate `(field_id, year)` rows found.\n")

    md.append("\n## 5. Crop label consistency\n")
    if label_mismatch_rows:
        mm = pd.DataFrame(label_mismatch_rows).drop_duplicates(["field_id", "year", "standard_name", "prod_crop_ru"])
        md.append(f"Found {len(mm)} unique label mismatches between Cropwise history crop and productivity_data crop.\n")
        md.append(code(mm.sort_values(["year", "field_id"]).head(80)))
    else:
        md.append("No crop label mismatches found.\n")

    md.append("\n## 6. High-missing features (>80%)\n")
    hm = pd.DataFrame(high_missing_rows)
    if hm.empty:
        md.append("No >80% missing feature columns.\n")
    else:
        # Show unique columns and average missingness across dates.
        hms = hm.groupby("column")["missing_ratio"].mean().sort_values(ascending=False).head(60).reset_index()
        md.append(code(hms.round(3)))

    md.append("\n## 7. Verdict\n\n")
    if bad_leakage_rows or duplicate_rows:
        md.append("Blocking issues found: fix leakage/duplicates before treating v12 as final baseline.\n")
    else:
        md.append("No blocking leakage/duplicate issue found. Main remaining risks: crop-label mismatches and sparse scout/soil features.\n")

    out = REPORTS / "V12_PIPELINE_SANITY_AUDIT.md"
    out.write_text("".join(md), encoding="utf-8")
    print(f"Wrote {out}")
    print(overview.to_string(index=False))
    print("leakage cols:", len(bad_leakage_rows))
    print("label mismatches:", len(pd.DataFrame(label_mismatch_rows).drop_duplicates(["field_id", "year", "standard_name", "prod_crop_ru"])) if label_mismatch_rows else 0)


if __name__ == "__main__":
    main()

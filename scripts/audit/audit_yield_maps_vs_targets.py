"""
Audit combine yield maps vs factual targets.

Yield maps are post-harvest ground truth candidates, not as-of features.
This script checks whether our row-level target_yield_t_ha agrees with
available yield map averages.

Output: reports/YIELD_MAPS_TARGET_AUDIT.md
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd

ROOT_DIR = Path(__file__).resolve().parents[2]
os.chdir(ROOT_DIR)
DATA_RAW = Path("data_raw")
DATA_PROCESSED = Path("data_processed")
REPORTS = Path("reports")


def pick_yield_value(row: pd.Series) -> float:
    for col in ["external_average", "totals.result.average.value"]:
        value = pd.to_numeric(row.get(col), errors="coerce")
        if pd.notna(value) and 0.1 <= float(value) <= 12.0:
            return float(value)
    value = pd.to_numeric(row.get("calculated_average"), errors="coerce")
    units = str(row.get("units", ""))
    if pd.notna(value):
        value = float(value)
        if units == "tonn_per_ha" and 0.1 <= value <= 12.0:
            return value
        if units == "tonn_per_acre" and 0.1 <= value <= 6.0:
            return value * 2.47105381
    return np.nan


def main() -> None:
    ym = pd.read_csv(DATA_RAW / "yield_maps.csv", low_memory=False)
    ym["created_at"] = pd.to_datetime(ym["created_at"], errors="coerce", utc=True).dt.tz_convert(None)
    ym["year"] = ym["created_at"].dt.year
    ym["yield_map_t_ha"] = ym.apply(pick_yield_value, axis=1)
    ym_valid = ym.dropna(subset=["field_id", "year", "yield_map_t_ha"]).copy()
    ym_valid["field_id"] = ym_valid["field_id"].astype(int)
    ym_valid["year"] = ym_valid["year"].astype(int)
    ym_valid = ym_valid[(ym_valid["yield_map_t_ha"] >= 0.2) & (ym_valid["yield_map_t_ha"] <= 10.0)]

    ym_agg = (
        ym_valid.groupby(["field_id", "year"])
        .agg(
            yield_map_n=("yield_map_t_ha", "size"),
            yield_map_mean_t_ha=("yield_map_t_ha", "mean"),
            yield_map_std_t_ha=("yield_map_t_ha", "std"),
            yield_map_min_t_ha=("yield_map_t_ha", "min"),
            yield_map_max_t_ha=("yield_map_t_ha", "max"),
        )
        .reset_index()
    )

    target = pd.read_csv(DATA_PROCESSED / "targets_factual_t_ha.csv")
    target = target[target["kept"]].copy()
    target = target[["field_id", "year", "standard_name", "target_yield_t_ha", "target_source"]]
    cmp = target.merge(ym_agg, on=["field_id", "year"], how="inner")
    cmp["diff_map_minus_target"] = cmp["yield_map_mean_t_ha"] - cmp["target_yield_t_ha"]
    cmp["abs_diff"] = cmp["diff_map_minus_target"].abs()

    md: list[str] = []
    md.append("# Yield Maps vs Factual Target Audit\n\n")
    md.append("Generated by `scripts/audit/audit_yield_maps_vs_targets.py`.\n\n")
    md.append("Yield maps are post-harvest data, so they are **not** used as forecast features. This audit checks target quality.\n\n")
    md.append("## Coverage\n\n")
    md.append(f"- Raw yield_maps rows: {len(ym)}\n")
    md.append(f"- Valid yield map rows with yield value: {len(ym_valid)}\n")
    md.append(f"- Distinct `(field_id, year)` yield-map pairs: {len(ym_agg)}\n")
    md.append(f"- Pairs overlapping factual target: {len(cmp)}\n\n")

    if cmp.empty:
        md.append("No overlap with factual targets.\n")
    else:
        md.append("## Error summary\n\n")
        summary = cmp[["yield_map_mean_t_ha", "target_yield_t_ha", "diff_map_minus_target", "abs_diff"]].describe().round(3)
        md.append(summary.to_markdown())
        md.append("\n\n")
        md.append("## Worst mismatches\n\n")
        worst = cmp.sort_values("abs_diff", ascending=False).head(30)
        md.append(worst[[
            "field_id", "year", "standard_name", "target_source", "target_yield_t_ha",
            "yield_map_mean_t_ha", "yield_map_n", "diff_map_minus_target", "abs_diff",
        ]].round(3).to_markdown(index=False))
        md.append("\n\n")
        md.append("## Interpretation\n\n")
        md.append("- `abs_diff > 1 t/ha` rows are target-quality suspects.\n")
        md.append("- If yield_maps are trusted, those rows should be corrected or excluded in a sensitivity experiment.\n")
        md.append("- Do not feed yield_maps to as-of models because they are harvest-time leakage.\n")

    out = REPORTS / "YIELD_MAPS_TARGET_AUDIT.md"
    out.write_text("".join(md), encoding="utf-8")
    print(f"Wrote {out}")
    if not cmp.empty:
        print(cmp.sort_values("abs_diff", ascending=False).head(12)[[
            "field_id", "year", "standard_name", "target_yield_t_ha", "yield_map_mean_t_ha", "abs_diff"
        ]].round(3).to_string(index=False))


if __name__ == "__main__":
    main()
